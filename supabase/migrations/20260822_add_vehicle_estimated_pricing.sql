-- Additive vehicle-based estimated pricing for the existing booking flow.
-- Existing vehicle, booking, job, and service identifiers are preserved.

create table if not exists public.service_pricing (
  service_id text not null,
  vehicle_category text not null,
  price numeric(10, 2) not null,
  pricing_type text not null default 'estimated',
  active boolean not null default true,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  primary key (service_id, vehicle_category),
  constraint service_pricing_vehicle_category_check check (
    vehicle_category in ('small', 'mid_size', 'suv_premium')
  ),
  constraint service_pricing_type_check check (
    pricing_type in ('estimated', 'from')
  ),
  constraint service_pricing_price_check check (price > 0)
);

create table if not exists public.vehicle_pricing_overrides (
  vehicle_model_id bigint primary key
    references public.vehicle_models(id) on delete cascade,
  pricing_category text not null,
  notes text,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  constraint vehicle_pricing_overrides_category_check check (
    pricing_category in ('small', 'mid_size', 'suv_premium')
  )
);

create table if not exists public.vehicle_pricing_make_rules (
  normalized_make text primary key,
  pricing_category text not null,
  mapping_reason text not null,
  active boolean not null default true,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  constraint vehicle_pricing_make_rules_category_check check (
    pricing_category in ('small', 'mid_size', 'suv_premium')
  ),
  constraint vehicle_pricing_make_rules_reason_check check (
    mapping_reason in ('premium_make', 'suv_make')
  )
);

create table if not exists public.vehicle_pricing_model_rules (
  id bigint generated by default as identity primary key,
  normalized_make text,
  normalized_model_pattern text not null,
  pricing_category text not null,
  mapping_reason text not null,
  priority integer not null,
  active boolean not null default true,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  constraint vehicle_pricing_model_rules_category_check check (
    pricing_category in ('small', 'mid_size', 'suv_premium')
  ),
  constraint vehicle_pricing_model_rules_reason_check check (
    mapping_reason in ('suv_model_rule', 'small_model_rule', 'mid_size_model_rule')
  ),
  constraint vehicle_pricing_model_rules_priority_check check (priority > 0),
  constraint vehicle_pricing_model_rules_pattern_check check (
    btrim(normalized_model_pattern) <> ''
  )
);

create unique index if not exists vehicle_pricing_model_rules_unique_idx
  on public.vehicle_pricing_model_rules (
    coalesce(normalized_make, ''),
    normalized_model_pattern,
    pricing_category
  );

create index if not exists vehicle_pricing_model_rules_lookup_idx
  on public.vehicle_pricing_model_rules (active, priority, normalized_make);

create index if not exists service_pricing_active_lookup_idx
  on public.service_pricing (vehicle_category, active, service_id);

create or replace function public.set_vehicle_pricing_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = timezone('utc'::text, now());
  return new;
end;
$$;

