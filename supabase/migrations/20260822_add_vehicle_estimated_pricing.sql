create or replace function public.get_vehicle_service_pricing(
  p_vehicle_model_id bigint default null,
  p_make text default null,
  p_model text default null,
  p_service_ids text[] default array[]::text[]
)
returns table (
  vehicle_model_id bigint,
  vehicle_category text,
  mapping_reason text,
  service_id text,
  price numeric,
  pricing_type text
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_vehicle_model_id bigint;
  v_vehicle_category text;
  v_mapping_reason text;
begin
  select
    classification.vehicle_model_id,
    classification.pricing_category,
    classification.mapping_reason
  into
    v_vehicle_model_id,
    v_vehicle_category,
    v_mapping_reason
  from public.classify_vehicle_pricing(
    p_vehicle_model_id,
    p_make,
    p_model
  ) classification
  limit 1;

  return query
  select
    v_vehicle_model_id,
    v_vehicle_category,
    v_mapping_reason,
    pricing.service_id,
    pricing.price,
    pricing.pricing_type
  from public.service_pricing pricing
  where pricing.active
    and pricing.vehicle_category = v_vehicle_category
    and pricing.service_id = any(p_service_ids)
  order by array_position(p_service_ids, pricing.service_id);
end;
$$;

