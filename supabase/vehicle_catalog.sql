create table if not exists public.vehicle_makes (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer,
  is_popular boolean not null default false,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.vehicle_models (
  id bigint generated by default as identity primary key,
  make_id bigint not null references public.vehicle_makes(id) on delete cascade,
  name text not null,
  sort_order integer,
  is_popular boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  unique (make_id, name)
);

create table if not exists public.vehicle_model_fuels (
  id bigint generated by default as identity primary key,
  model_id bigint not null references public.vehicle_models(id) on delete cascade,
  fuel_type text not null,
  sort_order integer,
  created_at timestamptz not null default timezone('utc', now()),
  unique (model_id, fuel_type)
);

create table if not exists public.vehicle_model_engine_sizes (
  id bigint generated by default as identity primary key,
  model_id bigint not null references public.vehicle_models(id) on delete cascade,
  engine_size_simple integer,
  engine_size_desc text not null,
  sort_order integer,
  created_at timestamptz not null default timezone('utc', now()),
  unique (model_id, engine_size_desc)
);

create table if not exists public.vehicle_model_years (
  id bigint generated by default as identity primary key,
  model_id bigint not null references public.vehicle_models(id) on delete cascade,
  year integer not null,
  sort_order integer,
  created_at timestamptz not null default timezone('utc', now()),
  unique (model_id, year)
);

create index if not exists vehicle_models_make_id_idx
  on public.vehicle_models (make_id);

create index if not exists vehicle_models_make_id_sort_idx
  on public.vehicle_models (make_id, sort_order, name);

create index if not exists vehicle_model_fuels_model_id_idx
  on public.vehicle_model_fuels (model_id, sort_order, fuel_type);

create index if not exists vehicle_model_engine_sizes_model_id_idx
  on public.vehicle_model_engine_sizes (model_id, sort_order, engine_size_simple, engine_size_desc);

create index if not exists vehicle_model_years_model_id_idx
  on public.vehicle_model_years (model_id, sort_order, year);

